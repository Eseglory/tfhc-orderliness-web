// Generates an independent SQLite client; never connects to a database.
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'prisma/schema.prisma'), 'utf8');
const enums = new Map([...source.matchAll(/enum (\w+)\s*\{([^}]+)\}/g)].map(match =>
  [match[1], match[2].split(/\s+/).filter(Boolean)]));
const dateFields = {};
let model;
const converted = source.replace(/enum \w+\s*\{[^}]+\}/g, '').split(/\r?\n/).map(line => {
  const modelMatch = line.match(/^model (\w+)/);
  if (modelMatch) model = modelMatch[1];
  const field = line.match(/^(\s+)(\w+)(\s+)(\w+)(\[\]|\?)?(.*)$/);
  if (!field || !model) return line;
  let [, space, name, gap, type, suffix = '', tail] = field;
  if (/@db\.Date\b/.test(tail)) (dateFields[model] ||= []).push(name);
  tail = tail.replace(/\s+@db\.\w+(?:\([^)]*\))?/g, '');
  if (enums.has(type)) {
    type = 'String';
    tail = tail.replace(/@default\((\w+)\)/, '@default("$1")');
  } else if (type === 'Json' || suffix === '[]' && ['String','Int','Boolean','Float'].includes(type)) {
    type = 'String';
    if (suffix === '[]') { suffix = ''; tail = tail.replace('@default([])', '@default("[]")'); }
  }
  return space + name + gap + type + suffix + tail;
}).join('\n').replace('provider = "postgresql"', 'provider = "sqlite"')
  .replace('env("DATABASE_URL")', 'env("SQLITE_DATABASE_URL")')
  .replace('provider = "prisma-client-js"', 'provider = "prisma-client-js"\n  output = "../generated/sqlite-client"');
fs.mkdirSync(path.join(root, 'generated'), { recursive: true });
const schema = path.join(root, 'prisma/schema.sqlite.prisma');
fs.writeFileSync(schema, '// Generated by scripts/generate-sqlite.cjs; do not edit.\n' + converted);
fs.writeFileSync(path.join(root, 'generated/sqlite-date-fields.json'), JSON.stringify(dateFields, null, 2));
const cli = require.resolve('prisma/build/index.js');
const env = { ...process.env, SQLITE_DATABASE_URL: 'file:unused-generation-only.db' };
for (const args of [['generate', '--schema', schema], ['migrate', 'diff', '--from-empty', '--to-schema-datamodel', schema, '--script']]) {
  const result = spawnSync(process.execPath, [cli, ...args], { cwd: root, env, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 });
  if (result.status !== 0) { console.error('SQLite client generation failed.'); process.exit(1); }
  if (args[0] === 'migrate') fs.writeFileSync(path.join(root, 'generated/sqlite-schema.sql'), result.stdout);
}
console.log('Independent SQLite client and schema generated; no database connections made.');
